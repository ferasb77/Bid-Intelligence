def _zip(entries: dict[str, bytes]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as z:
        for name, data in entries.items():
            z.writestr(name, data)
    return buf.getvalue()


def _docx(paragraphs: list[str], *, wrap_in_sdt: bool = False) -> bytes:
    import docx
    from docx.oxml.ns import qn
    from lxml import etree
    d = docx.Document()
    for p in paragraphs:
        d.add_paragraph(p)
    if wrap_in_sdt:
        body = d.element.body
        paras = [c for c in body.iterchildren() if c.tag == qn("w:p")]
        sdt = etree.SubElement(body, qn("w:sdt"))
        content = etree.SubElement(sdt, qn("w:sdtContent"))
        body.remove(sdt)
        paras[0].addprevious(sdt)
        for p in paras:
            content.append(p)
    buf = io.BytesIO()
    d.save(buf)
    return buf.getvalue()


