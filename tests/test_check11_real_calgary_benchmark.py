class TestPersistedRoundTrip:
    def _rows(self, package, bid_id):
        payload = sp.build_persistence_payload(package)
        docs = [dict(d, id=i + 1, bid_id=bid_id, package_snapshot_id=7) for i, d in enumerate(payload["documents"])]
        items = [dict(e, bid_id=bid_id, package_snapshot_id=7) for e in payload["evidence_items"]]
        return payload, docs, items

    def test_rebuild_from_rows_is_lossless(self):
        pkg = sp.build_submission_package(cal.calgary_submission_zip(), bid_id=BID, organization_id=ORG)
        payload, docs, items = self._rows(pkg, BID)
        again = sp.package_from_persisted_rows(BID, ORG, pkg.package_digest, docs, items)
        p2 = sp.build_persistence_payload(again)
        key = lambda x: json.dumps(x, sort_keys=True, default=str)
        assert sorted(map(key, p2["documents"])) == sorted(map(key, payload["documents"]))
        assert sorted(map(key, p2["evidence_items"])) == sorted(map(key, payload["evidence_items"]))
        reqs = cal.live_requirements() + cal.synthetic_requirements()
        a = [m.to_dict() for m in sp.map_requirements_to_submission(reqs, pkg)]
        b = [m.to_dict() for m in sp.map_requirements_to_submission(reqs, again)]
        assert a == b

    def test_foreign_bid_row_fails_closed(self):
        pkg = sp.build_submission_package(cal.calgary_submission_files(), bid_id=BID, organization_id=ORG)
        _, docs, items = self._rows(pkg, BID)
        docs[0]["bid_id"] = BID + 1
        with pytest.raises(sp.CrossBidEvidenceError):
            sp.package_from_persisted_rows(BID, ORG, pkg.package_digest, docs, items)
        _, docs, items = self._rows(pkg, BID)
        items[0]["bid_id"] = BID + 1
        with pytest.raises(sp.CrossBidEvidenceError):
            sp.package_from_persisted_rows(BID, ORG, pkg.package_digest, docs, items)


class _FakeDB:
    def __init__(self):
        self.snapshots, self.docs, self.items, self.calls = {}, [], [], []

    def get_or_create_proposal_package_snapshot(self, bid_id, digest, manifest, uid=None):
        self.calls.append("snapshot")
        for s in self.snapshots.values():
            if s["bid_id"] == bid_id and s["package_digest"] == digest:
                return s
        sid = len(self.snapshots) + 1
        self.snapshots[sid] = {"id": sid, "bid_id": bid_id, "package_version": 1, "package_digest": digest,
                               "manifest": manifest}
        return self.snapshots[sid]

    def get_proposal_package_snapshot(self, sid):
        return self.snapshots.get(sid)

    def get_submission_documents(self, bid_id, sid):
        return [d for d in self.docs if d["bid_id"] == bid_id and d["package_snapshot_id"] == sid]

    def get_submission_evidence_items(self, bid_id, sid):
        return [i for i in self.items if i["bid_id"] == bid_id and i["package_snapshot_id"] == sid]

    def create_submission_evidence_bundle(self, bid_id, sid, cv, docs, items):
        self.calls.append("bundle")
        if self.get_submission_documents(bid_id, sid):
            return 0
        self.docs += [dict(d, id=len(self.docs) + i + 1, bid_id=bid_id, package_snapshot_id=sid) for i, d in enumerate(docs)]
        self.items += [dict(e, bid_id=bid_id, package_snapshot_id=sid) for e in items]
        return len(items)


