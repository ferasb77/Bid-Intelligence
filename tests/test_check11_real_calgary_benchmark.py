@needs_bidder_zip
class TestRealRequirementMapping:
    @pytest.fixture(scope="class")
    def mappings(self, real_pkg):
        return {m.req_id: m for m in sp.map_requirements_to_submission(_canon()["requirements"], real_pkg)}

    def test_no_requirement_permits_an_absence_claim(self, mappings):
        assert not [k for k, m in mappings.items() if m.artifact_status == sp.MISSING_FROM_PACKAGE]
        assert {m.artifact_status for m in mappings.values()} <= {sp.ARTIFACT_PRESENT, sp.POSSIBLY_PORTAL_NATIVE}

    def test_pricing_requirements_map_to_price_form_cells(self, mappings, real_pkg):
        pricing = [m for m in mappings.values() if m.expected.evidence_category == sp.EVIDENCE_CATEGORY_PRICING
                   and m.expected.roles == (sp.ROLE_PRICING_FORM,)]
        assert len(pricing) >= 5
        for m in pricing:
            assert m.primary_role_present and m.candidates
            assert real_pkg.document(m.candidates[0].submission_document_id).document_role == sp.ROLE_PRICING_FORM

    def test_appendix_e_declarations_map_to_the_submission_form(self, mappings, real_pkg):
        decl = [m for m in mappings.values() if m.expected.evidence_category == sp.EVIDENCE_CATEGORY_DECLARATION]
        assert decl
        for m in decl:
            assert m.primary_role_present
            assert real_pkg.document(m.candidates[0].submission_document_id).document_role == sp.ROLE_SUBMISSION_FORM

    def test_multi_party_clause_maps_to_b2(self, mappings, real_pkg):
        m = mappings["SUPP-B2-VERBATIM"]
        assert m.expected.roles[0] == sp.ROLE_MULTI_PARTY_FORM and m.primary_role_present
        b2 = real_pkg.documents_with_roles([sp.ROLE_MULTI_PARTY_FORM], include_secondary=False)[0]
        assert m.candidates[0].submission_document_id == b2.submission_document_id

    def test_rated_criteria_map_to_technical_sections(self, real_pkg):
        crits = [{"criterion_label": c["criterion_label"], "weight": c["weight"]}
                 for c in _canon()["rfp_evaluation_criteria"]]
        got = {c.criterion_label: c for c in sp.map_evaluation_criteria_to_sections(crits, real_pkg)}
        assert got["Firm Experience"].candidate_sections[0]["label"] == "PART 3 FIRM EXPERIENCE"
        assert got["Team Experience and Qualifications"].candidate_sections[0]["label"] == \
            "PART 4 TEAM EXPERIENCE AND QUALIFICATIONS"
        assert any("SCOPE OF SERVICES" in s["label"] or s["label"].startswith("3.")
                   for s in got["Service Delivery"].candidate_sections)
        # No Social Procurement section exists in Appendix C: only weak body matches, never a heading hit.
        assert all(s["score"] < 1.0 for s in got["Social Procurement"].candidate_sections)
